// Shared conversion logic. Runs in the service worker and in extension pages.
// Everything happens locally: the image is fetched, re-encoded on a canvas, and downloaded.

export const FORMATS = [
  { id: 'png', label: 'PNG', mime: 'image/png', ext: 'png' },
  { id: 'jpg', label: 'JPG', mime: 'image/jpeg', ext: 'jpg' },
  { id: 'webp', label: 'WebP', mime: 'image/webp', ext: 'webp' },
];

export function getFormat(id) {
  return FORMATS.find((f) => f.id === id);
}

// http(s) images on other origins need a host permission to be read.
export function originPattern(srcUrl) {
  const u = new URL(srcUrl);
  if (u.protocol !== 'http:' && u.protocol !== 'https:') return null;
  return `${u.origin}/*`;
}

export async function hasAccess(srcUrl) {
  const pattern = originPattern(srcUrl);
  if (!pattern) return true; // data: URLs need no permission
  return chrome.permissions.contains({ origins: [pattern] });
}

export async function convertAndDownload(srcUrl, format) {
  if (srcUrl.startsWith('blob:')) {
    throw new Error('This image is generated by the page itself (blob: URL) and cannot be read by extensions.');
  }

  const res = await fetch(srcUrl, { credentials: 'include' });
  if (!res.ok) throw new Error(`Could not load the image (HTTP ${res.status}).`);
  const blob = await res.blob();

  let bitmap;
  try {
    bitmap = await createImageBitmap(blob);
  } catch {
    throw new Error(`This image type (${blob.type || 'unknown'}) can't be converted yet.`);
  }

  const canvas = new OffscreenCanvas(bitmap.width, bitmap.height);
  const ctx = canvas.getContext('2d');
  if (format.mime === 'image/jpeg') {
    // JPG has no transparency: paint white instead of black.
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
  }
  ctx.drawImage(bitmap, 0, 0);
  bitmap.close();

  const out = await canvas.convertToBlob({ type: format.mime, quality: 0.92 });
  await chrome.downloads.download({
    url: await blobToDataUrl(out),
    filename: makeFilename(srcUrl, format.ext),
    saveAs: true,
  });
}

// URL.createObjectURL is unavailable in MV3 service workers, so use a data: URL.
async function blobToDataUrl(blob) {
  const bytes = new Uint8Array(await blob.arrayBuffer());
  let binary = '';
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk) {
    binary += String.fromCharCode.apply(null, bytes.subarray(i, i + chunk));
  }
  return `data:${blob.type};base64,${btoa(binary)}`;
}

export function makeFilename(srcUrl, ext) {
  let base = 'image';
  try {
    const u = new URL(srcUrl);
    if (u.protocol === 'http:' || u.protocol === 'https:') {
      const last = decodeURIComponent(u.pathname.split('/').filter(Boolean).pop() || '');
      const stem = last.replace(/\.[a-z0-9]{2,5}$/i, '');
      if (stem) base = stem;
    }
  } catch {
    /* keep default */
  }
  base = base.replace(/[^\w.-]+/g, '_').replace(/^[._]+/, '').slice(0, 100) || 'image';
  return `${base}.${ext}`;
}
